def A(aid, head, kicker, byline, sub, body, span=4, size="minor",
      cols=1, image=None, boxed=False, verse=False, imgh=None, fill=False,
      portrait=None, imgSide=None, imgW=None, ledeCols=None, caption=None):
    """aid 에 None 을 주면 원문 링크를 달지 않습니다.

    지면에 싣는 글은 대개 구름헤럴드에 올라간 기사의 요약이고, 전문은
    원문으로 보냅니다. 그런데 지면에만 싣는 글(현장 기사·칼럼)도 있습니다.
    그런 글에 원문 링크를 달면 없는 주소로 독자를 보내게 됩니다.

    image 가 'images/' 로 시작하면 우리 저장소에 둔 사진으로 봅니다.
    """
    b = {
        "type": "article", "span": span, "size": size, "cols": cols,
        "kicker": kicker, "head": head, "byline": byline + " 기자",
        "subtitle": sub, "body": body,
    }
    if aid is not None:
        b["link"] = LINK + str(aid)
    if image:
        b["image"] = image if image.startswith("images/") else IMG + image
        b["caption"] = caption or "사진 = 구름헤럴드"
        if imgh:
            b["imgh"] = imgh
        # imgSide = 사진 옆으로 흐를 문단 수. 사진이 본문 중간에 놓입니다.
        if imgSide:
            b["imgSide"] = imgSide
            if imgW: b["imgW"] = imgW
            if ledeCols: b["ledeCols"] = ledeCols
    if portrait:
        b["portrait"] = {"name": portrait}
    if boxed:
        b["boxed"] = True
    if verse:
        b["verse"] = True
    if fill:
        b["fill"] = True
    return b


def TABLE(span, title, head, rows, note=None, source=None):
    b = {"type": "table", "span": span, "title": title, "head": head, "rows": rows}
    if note: b["note"] = note
    if source: b["source"] = source
    return b


def CHART(span, title, rows, note=None, source=None, max=None,
          baseline=None, baselineLabel=None):
    b = {"type": "chart", "span": span, "title": title, "rows": rows}
    if note: b["note"] = note
    if source: b["source"] = source
    if max: b["max"] = max
    if baseline is not None:
        b["baseline"] = baseline
        if baselineLabel: b["baselineLabel"] = baselineLabel
    return b


def QUOTE(span, text, who):
    return {"type": "quote", "span": span, "text": text, "who": who}


def AD(span, label, note):
    return {"type": "ad", "span": span, "label": label, "note": note, "fill": True}


